#!/usr/bin/env python3
"""Distribute canonical brand assets; --check reports stale app copies."""

from __future__ import annotations

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BRAND = ROOT / "assets/brand"


def outputs(player: bool = False) -> dict[Path, bytes]:
    files: dict[Path, bytes] = {}
    docs = ROOT / "apps/docs/docs"
    server = ROOT / "apps/server"
    cli = ROOT / "crates/cli/assets"
    for name in ("icon.svg", "app-icon.png", "wordmark.png", "full-logo.png", "mascot.png", "favicon.png",
                 "apple-touch-icon.png", "social-preview.png"):
        data = (BRAND / "images" / name).read_bytes()
        files[docs / "assets/brand" / name] = data
        files[server / "priv/static/images/brand" / name] = data
    files[cli / "favicon.png"] = (BRAND / "images/favicon.png").read_bytes()
    files[docs / "assets/logo.png"] = (BRAND / "images/favicon.png").read_bytes()
    files[server / "priv/static/images/favicon.png"] = (BRAND / "images/favicon.png").read_bytes()
    files[server / "lib/popcorn_web/controllers/recording_svg/logo.svg.heex"] = (
        BRAND / "images/icon.svg"
    ).read_bytes()
    tokens = (BRAND / "tokens.css").read_bytes()
    files[docs / "stylesheets/brand-tokens.css"] = tokens
    files[server / "assets/css/foundation/brand-tokens.css"] = tokens
    # Less must inline this copy so distributed/embedded players are self-contained.
    files[ROOT / "packages/player/src/less/brand-tokens.less"] = tokens
    for folder, url in ((docs / "assets/brand/fonts", "../assets/brand/fonts"),
                        (server / "priv/static/fonts/brand", "/fonts/brand")):
        for font in (BRAND / "fonts").glob("*"):
            if font.suffix in (".woff2", ".txt"):
                files[folder / font.name] = font.read_bytes()
        css = font_css(url)
        target = docs / "stylesheets/brand-fonts.css" if folder.is_relative_to(docs) else (
            server / "assets/css/fonts/brand.css"
        )
        files[target] = css.encode()
    if player:
        bundle = ROOT / "packages/player/dist/bundle"
        for name, target in (("popcorn-player.css", docs / "stylesheets/popcorn-player.css"),
                             ("popcorn-player.min.js", docs / "javascripts/popcorn-player.min.js")):
            data = (bundle / name).read_bytes()
            files[cli / name] = data
            files[target] = data
    return files


def font_css(url: str) -> str:
    rules = []
    for family, file, weight, style in (
        ("Plus Jakarta Sans", "PlusJakartaSans", "200 800", "normal"),
        ("JetBrains Mono", "JetBrainsMono-Regular", "400", "normal"),
        ("JetBrains Mono", "JetBrainsMono-Bold", "700", "normal"),
        ("JetBrains Mono", "JetBrainsMono-Italic", "400", "italic"),
        ("JetBrains Mono", "JetBrainsMono-BoldItalic", "700", "italic"),
    ):
        rules.append(f'''@font-face {{
  font-family: '{family}';
  src: url('{url}/{file}.woff2') format('woff2');
  font-weight: {weight};
  font-style: {style};
  font-display: swap;
}}
''')
    return "/* Generated by scripts/sync_brand.py. */\n" + "\n".join(rules)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--player", action="store_true", help="also copy the freshly built player bundle")
    args = parser.parse_args()
    stale = []
    for path, data in outputs(args.player).items():
        if path.exists() and path.read_bytes() == data:
            continue
        if args.check:
            stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    if stale:
        raise SystemExit("Stale brand assets; run python3 scripts/sync_brand.py:\n" + "\n".join(stale))
    print("Brand assets are current." if args.check else "Brand assets synchronized.")


if __name__ == "__main__":
    main()
